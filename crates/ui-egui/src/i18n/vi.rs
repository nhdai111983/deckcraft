//! feature names are translated, never its other wording.
//!
//! Keys are the English labels exactly as the code draws them; a label broken over two lines
//! (`New\nSlide`) is keyed with the lines joined by a space (`New Slide`).

use std::collections::HashMap;
use std::sync::OnceLock;

pub(super) fn translate(text: &str) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| ENTRIES.iter().copied().collect()).get(text).copied()
}

